// Vite plugin: fills index.html's share tags and structured data from the
// site's data files, and builds one static page per share-preview variant.
//
// Why at build time: link-preview crawlers (Messages, WhatsApp, Facebook, X)
// read the raw HTML and never run the React app, so these tags have to be in
// the static files. Generating them from src/data keeps the review figures in
// one place (SITE.rating) instead of three hand-maintained copies.
import fs from 'node:fs'
import path from 'node:path'
import { SITE } from '../src/data/site.js'
import { SHARE_DEFAULTS, SHARE_PREVIEWS } from '../src/data/sharePreviews.js'

const escapeHtml = (value) =>
  String(value).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c])

// Width/height straight from the file header (PNG IHDR, JPEG SOFn), so the
// og:image:width/height tags are always true to the file.
function imageInfo(file) {
  const buf = fs.readFileSync(file)
  if (buf.readUInt32BE(0) === 0x89504e47) {
    return { type: 'image/png', width: buf.readUInt32BE(16), height: buf.readUInt32BE(20), bytes: buf.length }
  }
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2
    while (i < buf.length) {
      if (buf[i] !== 0xff) { i += 1; continue }
      const marker = buf[i + 1]
      const sof = marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)
      if (sof) return { type: 'image/jpeg', height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7), bytes: buf.length }
      i += 2 + buf.readUInt16BE(i + 2)
    }
  }
  throw new Error(`${file}: not a PNG or JPEG`)
}

function ratingSentence() {
  const { stars, reviews } = SITE.rating
  return `Rated ${stars} across ${reviews} reviews.`
}

function structuredData(siteUrl) {
  const digits = SITE.phoneHref.replace(/\D/g, '') // 16463771575
  const data = {
    '@context': 'https://schema.org',
    '@type': 'LocalBusiness',
    name: SITE.name,
    image: `${siteUrl}share-17-years.jpg`,
    url: SITE.websiteHref,
    telephone: `+${digits[0]}-${digits.slice(1, 4)}-${digits.slice(4, 7)}-${digits.slice(7)}`,
    email: SITE.email,
    foundingDate: String(SITE.established),
    address: {
      '@type': 'PostalAddress',
      streetAddress: SITE.address.street,
      addressLocality: SITE.address.city,
      addressRegion: SITE.address.region,
      postalCode: SITE.address.zip,
      addressCountry: 'US',
    },
    areaServed: [{ '@type': 'City', name: 'New York City' }],
    makesOffer: ['Dog Daycare', 'Dog Walking', 'Pet Sitting', 'Vacation Care'].map((name) => ({
      '@type': 'Offer',
      itemOffered: { '@type': 'Service', name },
    })),
    sameAs: [SITE.social.instagram.href, SITE.social.facebook.href],
  }
  // Only once the figures are confirmed (see SITE.rating.verified). A
  // structured-data rating is a claim made to search engines, and Google does
  // not accept ratings collected on other sites as a business's own rating.
  if (SITE.rating.verified) {
    data.aggregateRating = {
      '@type': 'AggregateRating',
      ratingValue: String(SITE.rating.stars),
      reviewCount: String(SITE.rating.reviews),
    }
  }
  return JSON.stringify(data, null, 2).replace(/</g, '\\u003c')
}

function previewPage(siteUrl, variant, info) {
  const title = variant.title || SHARE_DEFAULTS.title
  const description = variant.description || `${SHARE_DEFAULTS.description} ${ratingSentence()}`
  const pageUrl = `${siteUrl}share/${variant.id}/`
  const imageUrl = `${siteUrl}${variant.image}`
  const e = escapeHtml
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <!-- Share-preview variant "${e(variant.id)}". Generated by scripts/site-meta.js
         from src/data/sharePreviews.js; edit that file, not this one. -->
    <meta name="robots" content="noindex, nofollow" />
    <title>${e(title)}</title>
    <meta name="description" content="${e(description)}" />
    <link rel="canonical" href="${e(pageUrl)}" />

    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="${e(SITE.name)}" />
    <meta property="og:title" content="${e(title)}" />
    <meta property="og:description" content="${e(description)}" />
    <meta property="og:url" content="${e(pageUrl)}" />
    <meta property="og:image" content="${e(imageUrl)}" />
    <meta property="og:image:secure_url" content="${e(imageUrl)}" />
    <meta property="og:image:type" content="${info.type}" />
    <meta property="og:image:width" content="${info.width}" />
    <meta property="og:image:height" content="${info.height}" />
    <meta property="og:image:alt" content="${e(variant.alt)}" />

    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:title" content="${e(title)}" />
    <meta name="twitter:description" content="${e(description)}" />
    <meta name="twitter:image" content="${e(imageUrl)}" />
    <meta name="twitter:image:alt" content="${e(variant.alt)}" />

    <link rel="icon" href="../../favicon.ico" sizes="any" />
    <style>
      body { margin: 0; min-height: 100vh; display: grid; place-items: center; padding: 24px; box-sizing: border-box; background: #0f2b29; color: #fcfeff; font: 16px/1.5 system-ui, sans-serif; text-align: center; }
      img { display: block; width: min(100%, 600px); height: auto; margin: 0 auto 20px; border-radius: 6px; }
      small { display: block; margin-bottom: 20px; color: #86cacc; letter-spacing: 0.08em; text-transform: uppercase; }
      a { display: inline-block; padding: 14px 22px; background: #d69628; color: #0f2b29; font-weight: 700; text-decoration: none; }
    </style>
  </head>
  <body>
    <main>
      <img src="${e(imageUrl)}" alt="${e(variant.alt)}" width="${info.width}" height="${info.height}" />
      <small>Share preview: ${e(variant.label || variant.id)}</small>
      <a href="../../">Visit the ${e(SITE.name)} website</a>
    </main>
  </body>
</html>
`
}

export default function siteMeta({ siteUrl }) {
  const base = siteUrl.endsWith('/') ? siteUrl : `${siteUrl}/`
  let publicDir = 'public'

  return {
    name: 'prospectbark-site-meta',
    configResolved(config) {
      publicDir = config.publicDir
    },
    transformIndexHtml(html) {
      return html
        .replaceAll('{{SITE_URL}}', base)
        .replaceAll('{{SHARE_TITLE}}', escapeHtml(SHARE_DEFAULTS.title))
        .replaceAll('{{SHARE_DESCRIPTION}}', escapeHtml(`${SHARE_DEFAULTS.description} ${ratingSentence()}`))
        .replace('{{STRUCTURED_DATA}}', structuredData(base))
    },
    generateBundle() {
      const ids = new Set()
      for (const variant of SHARE_PREVIEWS) {
        if (ids.has(variant.id)) this.error(`share preview id "${variant.id}" is used twice`)
        ids.add(variant.id)
        const file = path.join(publicDir, variant.image)
        if (!fs.existsSync(file)) {
          this.warn(`share preview "${variant.id}" skipped: ${path.relative(process.cwd(), file)} is not there yet`)
          continue
        }
        const info = imageInfo(file)
        if (info.width < 600 || info.width / info.height < 1.6 || info.width / info.height > 2.1) {
          this.warn(`share preview "${variant.id}": ${info.width}x${info.height} is not ~1.91:1, so phones will crop it (1200x630 is ideal)`)
        }
        this.emitFile({ type: 'asset', fileName: `share/${variant.id}/index.html`, source: previewPage(base, variant, info) })
      }
    },
  }
}
